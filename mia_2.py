# --- 3. MIAModule (Attack LLM - this generates the question AND infers membership) ---
class MIAModule(dspy.Module):
    def __init__(self, attack_lm):
        super().__init__()
        self.question_generator = dspy.ChainOfThought(QuestionGenerationSignature)
        self.mia_inference = dspy.ChainOfThought(MIAInferenceSignature)
        
        # self.mia_possibility_inference = dspy.ChainOfThought(MIADigitalSignature)
        self.attack_lm = attack_lm
        

    def forward(self, news_sample_text, target_llm_answer=None, question_to_target_llm=None):
        # Phase 1: Generate the question for the Target LLM
        # This part is always executed to get the question.
        gen_question_output = self.question_generator(news_sample_text=news_sample_text)
        generated_question_str = gen_question_output.generated_question
        # generated_question_str = f"请判断以下新闻是否在被提供给你的训练上下文中：\n{news_sample_text} （是或否）\n 并回答理由"
        # Phase 2: Infer membership (only if target_llm_answer is provided, i.e., during actual inference/evaluation)
        # During compilation of MIAModule, target_llm_answer will be part of the 'example'
        # so this part will be invoked.
        if target_llm_answer is not None and question_to_target_llm is not None:
            # pdb.set_trace()
            # mia_result = self.mia_inference(
            #     original_news_sample_text=news_sample_text,
            #     question_to_target_llm=question_to_target_llm,
            #     target_llm_answer=target_llm_answer
            # )
            # pdb.set_trace()
            # return {
            #     "generated_question": generated_question_str, # Return the generated question
            #     "is_member": ("是" in mia_result.is_member) or ("True" in mia_result.is_member) or ("Yes" in mia_result.is_member),
            #     "score": float(mia_result.score) if mia_result.score.isdigit() else 0
            # }
            
            # pdb.set_trace()
            return {
                "generated_question": generated_question_str, # Return the generated question
                "is_member": ("是" in target_llm_answer) or ("True" in target_llm_answer) or ("Yes" in target_llm_answer),
                # "score": float(mia_result.score) if mia_result.score.isdigit() else 0
            }
        else:
            # During the first part of compilation or just generation, only return the question
            return {"generated_question": generated_question_str}

# --- 4. EnhancedClassifier (Target LLM - receives Attack LLM's question) ---
class EnhancedClassifier(dspy.Module):
    def __init__(self, target_lm, compiled_mia_module):
        super().__init__()
        self.classifier = dspy.ChainOfThought("contexts, question -> response, rationale")
        self.target_lm = target_lm
        self.mia_module = compiled_mia_module
        self.text_regenerator = dspy.ChainOfThought(SampleRegenerationSignature)

    def forward(self, contexts, original_news_sample_text):
        # 1. Attack LLM generates the question
        # This call to mia_module only generates the question, it doesn't infer membership yet.
        # Note: during compilation, `original_news_sample_text` is the `question` from overall_dev_examples.
        attack_llm_question_output = self.mia_module(news_sample_text=original_news_sample_text)
        question_to_target_llm = attack_llm_question_output["generated_question"]

        # 2. Target LLM answers the generated question
        
        classification_1 = self.classifier(contexts=contexts, question=question_to_target_llm)
        response_1 = classification_1.response
        rationale_1 = classification_1.rationale
        # target_llm_answer = f"回答: {response}, 理由: {rationale}"
        target_llm_answer = f"回答: {response_1}"
        # 3. Attack LLM infers membership based on its generated question and Target LLM's answer
        mia_result_1 = self.mia_module(
            news_sample_text=original_news_sample_text, # Original news text
            question_to_target_llm=question_to_target_llm, # The question it generated
            target_llm_answer=target_llm_answer # Target LLM's response
        )

        regeneration_text_2=self.text_regenerator(news_sample_text=original_news_sample_text).regenerated_text
        attack_llm_question_output = self.mia_module(news_sample_text=regeneration_text_2)
        question_to_target_llm_2 = attack_llm_question_output["generated_question"]
        classification_2 = self.classifier(contexts=contexts, question=question_to_target_llm_2)
        response_2 = classification_2.response
        rationale_2 = classification_2.rationale

        # target_llm_answer = f"回答: {response}, 理由: {rationale}"
        target_llm_answer = f"回答: {response_2}"
        # 3. Attack LLM infers membership based on its generated question and Target LLM's answer
        mia_result_2 = self.mia_module(
            news_sample_text=original_news_sample_text, # Original news text
            question_to_target_llm=question_to_target_llm, # The question it generated
            target_llm_answer=target_llm_answer # Target LLM's response
        )

        if(mia_result_1["is_member"] == mia_result_2["is_member"]):
            is_member = mia_result_1["is_member"]
            return dspy.Prediction(
                response=[response_1,response_2],
                rationale=[rationale_1,rationale_2],
                generated_question_by_attack_llm=[question_to_target_llm, question_to_target_llm_2], # New output
                is_member=is_member
                # score=mia_result["score"]
            )        

        else:
            is_member = True
            return dspy.Prediction(
                response=[response_1,response_2],
                rationale=[rationale_1,rationale_2],
                generated_question_by_attack_llm=[question_to_target_llm, question_to_target_llm_2], # New output
                is_member=is_member
                # score=mia_result["score"]
            )

        regeneration_text_3=self.text_regenerator(news_sample_text=regeneration_text_2).regenerated_text
        attack_llm_question_output = self.mia_module(news_sample_text=regeneration_text_3)
        question_to_target_llm_3 = attack_llm_question_output["generated_question"]
        classification_3 = self.classifier(contexts=contexts, question=question_to_target_llm_3)
        response_3 = classification_3.response
        rationale_3 = classification_3.rationale
        # target_llm_answer = f"回答: {response}, 理由: {rationale}"
        target_llm_answer = f"回答: {response_3}"
        # 3. Attack LLM infers membership based on its generated question and Target LLM's answer
        mia_result_3 = self.mia_module(
            news_sample_text=original_news_sample_text, # Original news text
            question_to_target_llm=question_to_target_llm, # The question it generated
            target_llm_answer=target_llm_answer # Target LLM's response
        )
        is_member_1 = mia_result_1["is_member"]
        is_member_2 = mia_result_2["is_member"]
        is_member_3 = mia_result_3["is_member"]

        cnt=(is_member_1==True) + (is_member_2==True) + (is_member_3==True)
        if cnt >= 2:
            is_member = True
        else:
            is_member = False
        return dspy.Prediction(
            response=[response_1,response_2,response_3],
            rationale=[rationale_1,rationale_2,rationale_3],
            generated_question_by_attack_llm=[question_to_target_llm, question_to_target_llm_2, question_to_target_llm_3], # New output
            is_member=is_member
            # score=mia_result["score"]
        )

