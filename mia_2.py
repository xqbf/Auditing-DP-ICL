# --- Data Generation for Overall Evaluation of EnhancedClassifier ---
# This is separate because it needs the 'contexts' for the target LLM

Num_context_samples = 1


def create_overall_evaluation_examples(data_pool, num_examples=100, num_context_samples=Num_context_samples):
    examples = []
    for _ in range(num_examples):
        is_member_in_current_context = random.choice([True, False])
        selected_context_samples = []
        question_data = None

        if is_member_in_current_context:
            target_sample = random.choice(data_pool)
            selected_context_samples.append(target_sample)
            remaining_samples_pool = [s for s in data_pool if s != target_sample]
            selected_context_samples.extend(random.sample(remaining_samples_pool, min(len(remaining_samples_pool), num_context_samples - 1)))
            question_data = target_sample
        else:
            selected_context_samples = random.sample(data_pool, num_context_samples)
            context_texts = {s[2] for s in selected_context_samples}
            non_member_candidates = [s for s in data_pool if s[2] not in context_texts]
            if not non_member_candidates:
                question_data = random.choice(data_pool)
            else:
                question_data = random.choice(non_member_candidates)
            is_member_in_current_context = question_data[2] in {s[2] for s in selected_context_samples}

        context_str = "\n".join(
            [f"文章: {sample[2]}\n分类: {types[int(sample[0])]}" for sample in selected_context_samples]
        )
        # The 'question' here is the original news text that will be used by Attack LLM to generate its query
        original_news_text_for_eval = question_data[2] 
        
        examples.append(dspy.Example(
            contexts=context_str, # Invisible context for the target LLM
            original_news_sample_text=original_news_text_for_eval, # Input for the Attack LLM to start its process
            category=types[int(question_data[0])], # Ground truth classification
            is_member=is_member_in_current_context # Ground truth for MIA (membership in *this* context)
        ).with_inputs("contexts", "original_news_sample_text")) # These are the inputs for EnhancedClassifier's forward
    return examples


# --- Evaluation Metric ---
def evaluate_overall_performance(example, pred, trace=None):
    try:
        # pred_category = getattr(pred, "category", "unknown")
        pred_is_member = getattr(pred, "is_member", False)
        
        # class_correct = example.category.lower() == pred_category.lower()
        mia_correct = (example.is_member == pred_is_member) 
        
        return (int(mia_correct)) 
    except Exception as e:
        print(f"评估函数错误: {str(e)}")
        return 0

def evaluate_mia_module(example, pred, trace=None):
    """
    这个 metric 正确处理来自 MIAModule 的字典输出。
    'pred' 是 MIAModule.forward() 返回的字典。
    'example' 是来自 mia_train_examples 的 dspy.Example。
    """
    # 从字典中安全地获取 'is_member' 的值
    pred_is_member = pred.get("is_member", False)
    
    # 进行正确的比较
    mia_correct = (example.is_member == pred_is_member)
    # pdb.set_trace()
    return mia_correct # 返回 True 或 False

