# # --- 2. Signature for Attack LLM to Infer Membership ---
class MIAInferenceSignature(dspy.Signature):
    """Based on the question generated by the Attack LLM and the Target LLM's answer, infer whether the news sample is a member of the Target LLM's training context."""
    original_news_sample_text = dspy.InputField(desc="原始新闻样本内容") # The raw text, for attack LLM's reference
    question_to_target_llm = dspy.InputField(desc="向目标LLM提出的问题") # The question generated by Attack LLM
    target_llm_answer = dspy.InputField(desc="目标LLM对问题的回复以及理由")
    is_member = dspy.OutputField(desc="Decide whether the news sample is a member of the LLM's training context. (Yes/No)")
    score = dspy.OutputField(desc="该样本是目标LLM训练上下文的成员的概率(0-100)")

class QuestionGenerationSignature(dspy.Signature):
    """
    Based on the target news sample, generate a direct and clear question to ask a large language model (LLM) whether it has seen the sample in its training data.
    The question should be straightforward, asking the LLM to decide if the news sample appears in its previous context, and provide a reason for its answer.
    The question should be structured to elicit a simple 'Yes' or 'No' response, followed by a rationale.
    Sample: Please decide whether the following news appears in your previous context: {news_sample_text} (Yes or No) and provide a reason.
    """
    # Sample: 'Please decide whether the following news appears in your previous context:\n{news_sample_text} (Yes or No)\n and provide a reason.'
    
    news_sample_text = dspy.InputField(desc="News sample text to be judged by the LLM")
    generated_question = dspy.OutputField(desc="Question to be posed to the target LLM")

class SampleRegenerationSignature(dspy.Signature):
    """
    Based on the news sample, rewrite the news text in a concise and clear manner, while preserving the original meaning.
    """
    news_sample_text = dspy.InputField(desc="原始新闻样本内容")
    # generated_question = dspy.InputField(desc="针对此新闻生成的问题")
    regenerated_text = dspy.OutputField(desc="Regenerated news text.")



